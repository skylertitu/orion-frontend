export function normalizeLocale(value: unknown): AppLocale {
  return typeof value === "string" && ALLOWED.has(value as AppLocale) ? (value as AppLocale) : "es";
}

export function getLocale(): AppLocale {
  if (typeof window === "undefined") return "es";
  try {
    return normalizeLocale(localStorage.getItem(STORAGE_KEY));
  } catch {
    return "es";
  }
}

export function setLocale(locale: unknown): AppLocale {
  const next = normalizeLocale(locale);
  if (typeof window === "undefined") return next;
  try {
    localStorage.setItem(STORAGE_KEY, next);
    document.documentElement.lang = next;
    document.documentElement.dir = next === "ar" ? "rtl" : "ltr";
    window.dispatchEvent(new Event(EVENT));
  } catch {
    /* ignore */
  }
  return next;
}

export function t(key: LocaleKey, locale = getLocale()): string {
  return DICT[locale]?.[key] || DICT.es[key];
}

export function subscribeLocale(onChange: () => void): () => void {
  if (typeof window === "undefined") return () => undefined;
  window.addEventListener(EVENT, onChange);
  return () => window.removeEventListener(EVENT, onChange);
}
